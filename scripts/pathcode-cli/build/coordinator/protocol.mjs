export function makeCoordinatorRequest(method, params = {}) {
  return {
    id: `${process.pid}-${Date.now()}-${Math.random().toString(16).slice(2)}`,
    method,
    params,
  };
}

export function makeCoordinatorError(id, code, message) {
  return { id, error: { code, message } };
}
